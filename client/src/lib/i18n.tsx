const I18nContext = createContext<I18nContextType | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window === "undefined") return "en";
    const saved = window.localStorage.getItem("margin-language");
    return saved === "ar" || saved === "en" ? (saved as Language) : "en";
  });

  // Keep <html dir/lang> and localStorage in sync with the active language.
  // We rely on this single effect (rather than mutating the DOM inside the
  // setter) so toggling repeatedly between "en" and "ar" always lands on a
  // consistent state, even if React batches multiple updates in one tick.
  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = language;
    try {
      window.localStorage.setItem("margin-language", language);
    } catch {
      // ignore storage errors (private mode etc.)
    }
  }, [language]);

  const setLanguage = useCallback((lang: Language) => {
    setLanguageState((prev) => (prev === lang ? prev : lang));
  }, []);

  const t = (key: string, replacements?: Record<string, string>): string => {
    let text = translations[language][key] || translations.en[key] || key;
    if (replacements) {
      Object.entries(replacements).forEach(([k, v]) => {
        text = text.replace(`{{${k}}}`, v);
      });
    }
    return text;
  };

  const isRTL = language === "ar";

  return (
    <I18nContext.Provider value={{ language, setLanguage, t, isRTL }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return context;
}

/**
 * Bridge component that mirrors the authenticated user's saved
 * `users.language` preference into the local i18n state. Mount this
 * once inside <AuthProvider> (so `useAuth()` is available) and inside
 * <I18nProvider> (so `useI18n()` is available).
 *
 * Behavior:
 * - When the server-side `user.language` value changes (login, refetch
 *   after a settings save, switching account), we apply it to the i18n
 *   state. The setter is a no-op if the value already matches, so this
 *   is safe to fire after a header toggle that already updated state
 *   locally and then PATCHed the server.
 * - We deliberately do NOT depend on the local `language` state, so
 *   that a user-initiated toggle doesn't get reverted by an in-flight
 *   stale `user.language` value.
 * - Anonymous visitors fall through to the existing localStorage-only
 *   behavior already handled by I18nProvider.
 */
export function LanguageSync() {
  const { user } = useAuth();
  const { setLanguage } = useI18n();
  // Track the (userId, language) pair we most recently applied. This lets
  // us re-apply the saved language on auth transitions (login → logout →
  // login again as the same user with the same persisted language) while
  // still no-op'ing within a single session so a header toggle is not
  // immediately reverted by a stale /api/auth/me cache.
  const lastAppliedRef = useRef<{ userId: string | null; lang: Language | null }>({
    userId: null,
    lang: null,
  });

  useEffect(() => {
    const userId = user?.id ?? null;
    const userLang = user?.language;
    // Reset our memo when the auth identity changes (logout, or a
    // different user logging in). After this reset, the very next render
    // with a real user will re-apply that user's saved language even if
    // it matches what we previously applied for someone else / for the
    // anonymous fallback.
    if (lastAppliedRef.current.userId !== userId) {
      lastAppliedRef.current = { userId, lang: null };
    }
    if (userLang !== "en" && userLang !== "ar") return;
    if (lastAppliedRef.current.lang === userLang) return;
    lastAppliedRef.current = { userId, lang: userLang };
    setLanguage(userLang);
  }, [user?.id, user?.language, setLanguage]);

  return null;
}
